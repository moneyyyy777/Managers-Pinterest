/**
 * Client-safe Prompt Builders (no Node.js 'fs' dependencies)
 */

export function buildArchitectureAdvisorPrompt({
  category = '',
  collection = '',
  siteUrl = '',
  localPath = '',
  pathMode = 'online',
  productsJson = null
} = {}) {
  const nicheName = collection
    ? (category ? `${category} ${collection}` : collection)
    : '[Название Ниши]';
  const effectiveCategory = category || '[Категория]';
  const effectiveCollection = collection || '[Подборка]';
  const finalUrl = siteUrl || `https://artify-studio.pages.dev/${effectiveCategory.toLowerCase()}/${effectiveCollection.toLowerCase()}`;
  const effectiveLocalPath = localPath || `Keywords/Artify Studio/${effectiveCategory}/${effectiveCollection}`;

  let productsSnippet = '(Товары коллекции не переданы в явном виде. Ориентируйся на тематику витрины, категорию и подборку.)';
  if (productsJson) {
    if (typeof productsJson === 'string') {
      productsSnippet = productsJson.trim();
    } else {
      try {
        productsSnippet = JSON.stringify(productsJson, null, 2);
      } catch {
        productsSnippet = String(productsJson);
      }
    }
  }

  const inputTargetStr = pathMode === 'local'
    ? `- Локальная папка проекта (Antigravity): ${effectiveLocalPath}\n- Каталог товаров: all_products.json (в папке ниши)`
    : `- URL витрины (Cloudflare): ${finalUrl}`;

  const promptText =
`Ты — Senior Pinterest Search Strategist, Product Taxonomist и Архитектор Коммерческой Семантики.
Твоя цель: провести глубокий анализ ниши "${nicheName}" и определить безошибочную архитектурную модель для продвижения на Pinterest перед сбором семантики и развертыванием папок в файловой структуре.

══════════════════════════════════════════════════════════════════
АРХИТЕКТУРНЫЕ МОДЕЛИ PINTEREST (ПРИНЦИП МАКСИМИЗАЦИИ ПРОДАЖ)
══════════════════════════════════════════════════════════════════

1) МОНО-ЯДРО (Single Core):
   - УСЛОВИЕ ВЫБОРА: Товары ниши объединены ЕДИНЫМ покупательским интентом, общей целевой аудиторией и совместимым контекстом применения.
   - СУТЬ: Все стили, модификации и вариации продукта естественным образом сосуществуют в одном визуальном и поисковом пространстве. Разные подстили не отпугивают покупателя, а дополняют выбор в рамках одной доски/кластера.
   - ПОЧЕМУ ОПАСНО ДРОБИТЬ: Если искусственно разделить моно-ядро на сегменты, поисковый вес размоется, возникнет каннибализация ключевых слов, а доски будут дублировать один и тот же спрос.

2) МУЛЬТИ-СЕГМЕНТ (Multi-Segment):
   - УСЛОВИЕ ВЫБОРА: Ниша охватывает РАЗНЫЕ независимые целевые аудитории, изолированные каналы монетизации, несовместимые сценарии использования (Use Cases) или полярные визуально-эстетические миры.
   - ⚠️ ФУНДАМЕНТАЛЬНОЕ ПРАВИЛО: Мульти-сегмент необходим НЕ ТОЛЬКО при разных типах физического или цифрового продукта, но и тогда, когда ОДИН И ТОТ ЖЕ ТИП ТОВАРА решает задачи принципиально разных рынков!
   - ПОЧЕМУ НЕЛЬЗЯ СМЕШИВАТЬ: 
     * Алгоритмы Pinterest группируют контент по визуальному сходству и совместным сохранениям (co-saves). Смешивание несовместимых стилей ломает алгоритмическое ранжирование.
     * Покупатель из одной индустрии/ниши мгновенно уходит, если в выдаче доски видит чужеродный для своего проекта контекст (падение CTR и конверсии).
     * Разные аудитории ищут продукт через совершенно разные семантические кластеры и ассоциативные цепочки.

═══ ВХОДНЫЕ ДАННЫЕ ═══
- Анализируемая ниша: ${nicheName}
- Базовая категория: ${effectiveCategory} / Коллекция: ${effectiveCollection}
${inputTargetStr}

Каталог / Товары витрины:
${productsSnippet}

══════════════════════════════════════════════════════════════════
КРИТЕРИИ АРХИТЕКТУРНОГО АУДИТА (БЕЗ ШАБЛОНОВ И ПРИВЯЗОК)
══════════════════════════════════════════════════════════════════
Проанализируй нишу по 4 универсальным осям:
1. Дифференциация покупательских персон (Buyer Personas): Приходят ли за этим товаром разные группы покупателей с непересекающимися потребностями, бюджетами и целями?
2. Каналы применения и сценарии (Use Cases / End-Applications): Существуют ли изолированные коммерческие индустрии, коммерческие проекты или сферы жизни, где применяется этот продукт?
3. Визуально-стилистическая совместимость: Могут ли пины по всем направлениям темы органично смотреться на одной Pinterest-доске без визуального и смыслового диссонанса?
4. Семантическая независимость поисковых потоков: Имеют ли направления собственный обособленный поисковый спрос в поисковой строке Pinterest, не смешивающийся с соседними ветками?

══════════════════════════════════════════════════════════════════
ТВОЁ ЗАДАНИЕ
══════════════════════════════════════════════════════════════════
1. Проведи объективный аудит темы "${nicheName}" и структуры каталога товаров.
2. Вынеси аргументированный вердикт: МОНО-ЯДРО или МУЛЬТИ-СЕГМЕНТ.
3. ЕСЛИ ТВОЙ ВЕРДИКТ — МУЛЬТИ-СЕГМЕНТ:
   - Сформируй полный перечень изолированных коммерческих сегментов (обычно 3–6 сегментов), которые закрывают 100% рыночного спроса данной темы без слепых зон.
   - Для КАЖДОГО сегмента укажи:
     а) Английское лаконичное название сегмента (готовое имя для папки проекта).
     б) Портрет целевого покупателя и его конкретный коммерческий сценарий (Use Case).
     в) Специфику визуального мира и позиционирования.
     г) Ключевые семантические триггеры, отличающие этот сегмент от остальных.
4. ЕСЛИ ТВОЙ ВЕРДИКТ — МОНО-ЯДРО:
   - Докажи, почему дробление на сегменты приведет к каннибализации и потере поискового веса.
   - Опиши единый портрет покупателя, глобальный сценарий использования и логику последующего распределения трафика через внутренние доски и интенты.`;

  return {
    promptText,
    category: effectiveCategory,
    collection: effectiveCollection,
    siteUrl: finalUrl,
    localPath: effectiveLocalPath,
    pathMode,
    nicheName,
    toString() {
      return this.promptText;
    }
  };
}

export function buildSeedTagsPrompt({
  category = '',
  collection = '',
  siteUrl = '',
  localPath = '',
  pathMode = 'online',
  architecture = 'single_core',
  segments = []
} = {}) {
  const nicheName = collection
    ? (category ? `${category} ${collection}` : collection)
    : '[Название Ниши]';
  const effectiveCategory = category || '[Категория]';
  const effectiveCollection = collection || '[Подборка]';
  const finalUrl = siteUrl || `https://artify-studio.pages.dev/${effectiveCategory.toLowerCase()}/${effectiveCollection.toLowerCase()}`;
  const effectiveLocalPath = localPath || `Keywords/Artify Studio/${effectiveCategory}/${effectiveCollection}`;

  const isMulti = architecture === 'multi_segment' || (Array.isArray(segments) && segments.length > 0);

  const inputTargetStr = pathMode === 'local'
    ? `- Локальная папка проекта (Antigravity): ${effectiveLocalPath}\n- Каталог товаров: all_products.json (в папке ниши)`
    : `- URL витрины (Cloudflare): ${finalUrl}`;

  let promptText = '';

  if (isMulti) {
    let segmentsListStr = '';
    if (Array.isArray(segments) && segments.length > 0) {
      segmentsListStr = segments
        .map((s, idx) => {
          const segName = typeof s === 'string' ? s : (s.name || `Сегмент ${idx + 1}`);
          return `- Сегмент ${idx + 1}: ${segName}`;
        })
        .join('\n');
    } else {
      segmentsListStr =
`- Выдели и проработай 3–6 ключевых изолированных сегментов рыночного спроса для ниши "${nicheName}".`;
    }

    promptText =
`Ты — Senior Pinterest Search Strategist, Lead Data Taxonomist и Архитектор Семантических Графов.
Твоя цель: создать исчерпывающие, изолированные банки поисковых seed tags для КАЖДОГО сегмента МУЛЬТИ-СЕГМЕНТНОЙ ниши "${nicheName}".

Эти seed tags предназначены для ввода в краулеры поисковых подсказок (PinInspector / Pinterest Autocomplete Engine) для последующего развертывания сотен коммерческих long-tail ключей.

ВХОДНЫЕ ДАННЫЕ:
- Ниша: ${nicheName}
${inputTargetStr}
- Архитектурная модель: Мульти-сегмент (Multi-Segment)

СЕГМЕНТЫ ДЛЯ ОБРАБОТКИ:
${segmentsListStr}

══════════════════════════════════════════════════════════════════
ПРИНЦИПЫ РАБОТЫ ПОИСКОВОГО ДВИЖКА PINTEREST (SEARCH MECHANICS)
══════════════════════════════════════════════════════════════════
1. Pinterest — это визуальная поисковая система с DA 94, где 97% поисковых запросов — unbranded (пользователи ищут решение, стиль, проект или готовый ассет, а не бренд).
2. Алгоритм автокомплита раскрывает дерево подсказок (Guided Search tiles) ТОЛЬКО при подаче точных 2–4 словных ядер. 
   - 1 слово — слишком абстрактно (дает случайный шум).
   - 5+ слов — автокомплит обрезает выдачу или возвращает пустой результат.
3. Задача seed tags — послужить идеальными корневыми семенами, из которых парсер вытянет максимальную глубину реального поискового спроса. Никаких искусственных ограничений по количеству семян: задача — покрыть ВСЕ возможные коммерческие вариации без единого белого пятна!

══════════════════════════════════════════════════════════════════
МАТРИЦА КОМБИНАТОРНОГО ПОКРЫТИЯ ДЛЯ КАЖДОГО СЕГМЕНТА
══════════════════════════════════════════════════════════════════
Для КАЖДОГО сегмента сначала составь комбинаторную матрицу компонентов, а затем сгенерируй полный банк семян путем их перекрестного пересечения:

1. Базовый актив (Core Entity): тип продукта и его синонимы в данной теме.
2. Сегментный вектор (Segment Core): специфический угол данного сегмента (индустрия, сфера применения).
3. Проекты и коммерческие сценарии (Use Cases / Projects): что именно создает или оформляет покупатель этим товаром.
4. Стилистические и эстетические маркеры сегмента: характерные стили, эпохи, визуальные атрибуты, свойственные только этому направлению.
5. Инструментарий и совместимость: форматы, средства реализации и крафтовые процессы (без запрещенных торговых марок).

══════════════════════════════════════════════════════════════════
ЖЕЛЕЗНЫЕ ПРАВИЛА КАЧЕСТВА SEED TAGS:
══════════════════════════════════════════════════════════════════
1. СТРОГАЯ ИЗОЛЯЦИЯ СЕГМЕНТОВ: Никаких смысловых и прямых пересечений между пулами разных сегментов! Теги сегмента А должны привлекать только свою целевую аудиторию и не смешиваться с сегментом Б.
2. ДЛИНА КЛЮЧА: Строго 2–4 слова. Никаких 1-словных и никаких 5+ словных конструкций.
3. ПОЛНОТА ОХВАТА: Не ограничивайся скромным списком. Создай исчерпывающий банк всех возможных релевантных связок (все валидные комбинации 2–4 слов, которые реально ищут покупатели).
4. ЧИСТОТА И БЕЗОПАСНОСТЬ:
   - Только английский язык, строчные буквы (lowercase).
   - Никаких спецсимволов (#, @, кавычки, слэши), никакой нумерации, точек и запятых.
   - СТРОГО БЕЗ мусорных слов 'free', 'download' и БЕЗ сторонних маркетплейсов/брендов (Etsy, Amazon, Creative Fabrica, Canva, Cricut и т.д.).
5. КОММЕРЧЕСКАЯ ЦЕННОСТЬ: Каждый тег обязан выражать намерение реального покупателя/мейкера/дизайнера найти продукт для реализации своей задачи.

ФОРМАТ ВЫВОДА:
Для каждого сегмента:
1. Краткая комбинаторная формула сегмента.
2. Отдельный блок кода markdown, содержащий ТОЛЬКО готовые seed tags (по одному на строку, чистый текст без нумерации и комментариев внутри блока), готовый для вставки в Seed Tags.txt.`;
  } else {
    promptText =
`Ты — Senior Pinterest Search Strategist, Lead Data Taxonomist и Архитектор Семантических Графов.
Твоя цель: создать исчерпывающий, всесторонний банк поисковых seed tags для МОНО-ЯДРА ниши "${nicheName}".

Эти seed tags предназначены для загрузки в краулеры поисковых подсказок (PinInspector / Pinterest Autocomplete Engine), чтобы развернуть глубокое семантическое дерево коммерческих запросов с долгосрочным потенциалом ранжирования.

ВХОДНЫЕ ДАННЫЕ:
- Ниша: ${nicheName}
${inputTargetStr}
- Архитектурная модель: Моно-ядро (Single Core)

══════════════════════════════════════════════════════════════════
МЕХАНИКА ПОИСКА PINTEREST И РОЛЬ SEED TAGS
══════════════════════════════════════════════════════════════════
1. Pinterest функционирует как визуально-поисковый каталог решений (DA 94, 97% unbranded поисковых сессий). Пользователи приходят с конкретным намерением создать проект, найти стиль или приобрести ассет.
2. Парсер подсказок (PinInspector) берет 2–4 словные семена и опрашивает API автокомплита Pinterest по алфавиту и ассоциациям, доставая длинные хвосты (long-tail keywords).
   - Если seed состоит из 1 слова — выдача будет замусорена общим некоммерческим контекстом.
   - Если seed состоит из 5+ слов — автокомплит Pinterest вернет пустоту.
3. В моно-ядре все подстили, техники и сценарии работают на одну общую аудиторию. Твоя задача — не ограничивать себя лимитами (не останавливаться на 20–30 штуках), а построить МАКСИМАЛЬНО ПОЛНЫЙ БАНК ВСЕХ ВОЗМОЖНЫХ КОМБИНАЦИЙ тегов из 2–4 слов, закрывающих нишу со всех ракурсов!

══════════════════════════════════════════════════════════════════
СИСТЕМНАЯ МАТРИЦА КОМБИНАЦИЙ (СЕМАНТИЧЕСКИЙ БАНК)
══════════════════════════════════════════════════════════════════
Перед формированием итогового списка проведи декомпозицию ниши на 5 базовых смысловых слоев:

Слой 1. Базовый объект / Ядро продукта (Core Entity): Существительное продукта и его прямые синонимы в теме.
Слой 2. Тематический дескриптор (Niche / Subject Anchor): Специфика темы, жанра или направления.
Слой 3. Сценарии применения и проекты (Use Cases / Commercial Output): Конкретные предметы, задачи или продукты, которые создает покупатель с помощью этого товара.
Слой 4. Эстетика, стили и визуальное настроение (Aesthetics & Mood): Визуальные подстили, исторические или современные эстетические течения, текстуры, ощущения.
Слой 5. Ролевой контекст и ремесло (Maker / Audience Context): Кто ищет продукт (дизайнеры, крафтеры, мейкеры, предприниматели) и тип крафтового процесса.

══════════════════════════════════════════════════════════════════
ГЕНЕРАЦИЯ ПОЛНОГО БАНКА СЕМЯН (2–4 СЛОВА)
══════════════════════════════════════════════════════════════════
Произведи системное перекрестное скрещивание слоев матрицы во всех жизнеспособных коммерческих сочетаниях:
- [Тематика] + [Базовый продукт]
- [Эстетика/Стиль] + [Тематика] + [Базовый продукт]
- [Тематика] + [Сценарий применения / Продукт]
- [Эстетика] + [Тематика] + [Сценарий]
- [Ремесло/Роль] + [Тематика] + [Базовый продукт]
- [Специфика стиля/формата] + [Тематика]

══════════════════════════════════════════════════════════════════
ЖЕЛЕЗНЫЕ ПРАВИЛА КАЧЕСТВА:
══════════════════════════════════════════════════════════════════
1. ДЛИНА: Строго 2, 3 или 4 слова в каждом теге. Никаких однословных понятий и никаких предложений из 5+ слов.
2. БЕЗ ЛИМИТОВ: Сгенерируй исчерпывающий, плотный банк всех возможных коммерческих комбинаций. Максимальный охват — нулевая терпимость к упущенному поисковому спросу.
3. ЧИСТОТА:
   - Только английский язык, строчные буквы (lowercase).
   - Никаких спецсимволов (#, @, кавычки, тире, слэши), никакой нумерации строк, точек и запятых.
   - СТРОГО БЕЗ стоп-слов ('free', 'download') и БЕЗ названий сторонних торговых площадок/брендов (Etsy, Amazon, Creative Fabrica, Canva, Cricut и др.).
4. РЕЛЕВАНТНОСТЬ И ИНТЕНТ: Каждый тег должен соответствовать реальному запросу в поисковой строке Pinterest от человека, готового применить данный продукт в своем деле.

ФОРМАТ ВЫВОДА:
1. Краткая схема смысловой матрицы ниши (выделенные слои).
2. Единый блок кода markdown, содержащий ИСКЛЮЧИТЕЛЬНО готовые seed tags (по одному на строку, чистый текст без нумерации, знаков препинания и пояснений), полностью готовый для копирования в файл Seed Tags.txt.`;
  }

  return {
    promptText,
    architecture: isMulti ? 'multi_segment' : 'single_core',
    segments: Array.isArray(segments) ? segments : [],
    category: effectiveCategory,
    collection: effectiveCollection,
    siteUrl: finalUrl,
    localPath: effectiveLocalPath,
    pathMode,
    nicheName,
    toString() {
      return this.promptText;
    }
  };
}
