def generate_description():
    """
    Генерирует короткие, емкие описания для Pinterest.
    Максимальная длина - 160 символов!
    """
    
    # 5 разных структур для разнообразия текста
    patterns = [
        # Паттерн 1: Hook + Assets + Use Case + CTA (Классика)
        # Пример: "✨ Welcome to the type universe! Premium fonts for branding & crafting. Explore the collection 👇"
        lambda: f"{random.choice(hooks)} {random.choice(assets).capitalize()} {random.choice(use_cases)} {random.choice(ctas)}",
        
        # Паттерн 2: Vibe + Assets + CTA (Коротко и эстетично)
        # Пример: "From elegant scripts to playful sans. Discover curated typefaces. Tap to download! ✨"
        lambda: f"{random.choice(vibes)}. Discover {random.choice(assets)}. {random.choice(ctas)}",
        
        # Паттерн 3: Hook + Vibe + Use Case + CTA (Максимально информативно)
        # Пример: "Elevate your design game. Aesthetic letterforms for any mood, perfect for crafters and designers. Find your perfect font 🔗"
        lambda: f"{random.choice(hooks)} {random.choice(vibes)}, {random.choice(use_cases)} {random.choice(ctas)}",
        
        # Паттерн 4: Без хука, сразу к делу
        # Пример: "Unique font bundles to bring your ideas to life. Timeless, bold, and crafted. Shop the typography bundle ⬇️"
        lambda: f"{random.choice(assets).capitalize()} {random.choice(use_cases)} {random.choice(vibes)}. {random.choice(ctas)}",
        
        # Паттерн 5: Ультра-короткий (Для аккаунтов-минималистов)
        # Пример: "Premium typography for creators. Find your perfect font 🔗"
        lambda: f"{random.choice(hooks)} {random.choice(ctas)}"
    ]
    
    # Генерируем описание
    bio = random.choice(patterns)()
    
    # ПРОВЕРКА НА ЛИМИТ ПИНТЕРЕСТА (160 символов)
    # Если получилось слишком длинно, генерируем заново
    if len(bio) > 160:
        return generate_description()
        
    return bio

